"""
Определение агентов для мультиагентной системы «Конвейер генерации контента».

Агенты:
- ResearcherAgent: исследователь, выполняет поиск информации
- WriterAgent: писатель, создаёт черновик статьи
- EditorAgent: редактор, проверяет качество
- PublisherAgent: публикатор, финализирует и сохраняет
"""

from swarm import Agent

from . import config
from .tools import search_web, search_yandex, search_tavily, save_article


# ---------------------------------------------------------------------------
# ResearcherAgent — сбор фактов по теме
# ---------------------------------------------------------------------------
RESEARCHER_INSTRUCTIONS = """
Ты — ResearcherAgent. Твоя роль — найти достоверную информацию по заданной теме для написания статьи.

У тебя есть три инструмента поиска:
1. search_web — DuckDuckGo (всегда доступен, без ключа)
2. search_yandex — Yandex Search API (доступен, если настроены API-ключ и Folder ID)
3. search_tavily — Tavily Search API (доступен, если настроен API-ключ)

Порядок работы:
1. Сначала используй search_web для поиска. Выполни поиск НЕ БОЛЕЕ 1 РАЗА.
2. Если search_web не дал результатов и search_yandex доступен — используй search_yandex.
3. Если search_yandex не дал результатов и search_tavily доступен — используй search_tavily.
4. Если все поиски ничего не нашли — сообщи об этом и передай пустой список.

Собери 5-7 наиболее релевантных источников (или сколько найдётся).
Для каждого источника укажи: заголовок, краткую выжимку (2-3 предложения) и ссылку.

После завершения передай собранные данные дальше по конвейеру. Не пиши статью — только собирай факты.
Будь объективен, используй разные источники.
"""

researcher_agent = Agent(
    name="Researcher",
    model=config.RESEARCHER_MODEL,
    instructions=RESEARCHER_INSTRUCTIONS,
    functions=[search_web, search_yandex, search_tavily],
)


# ---------------------------------------------------------------------------
# WriterAgent — написание черновика статьи
# ---------------------------------------------------------------------------
WRITER_INSTRUCTIONS = """
Ты — WriterAgent. Напиши качественную, структурированную статью по теме, используя предоставленные исследовательские данные.

Статья должна содержать:
1. Заголовок
2. Введение
3. Основную часть (2-4 раздела)
4. Заключение

Используй факты из research_data, но пиши своим языком — не копируй дословно.

Если тебе передали замечания редактора (поле editor_review), обязательно учти их при доработке.
Не выдумывай факты — опирайся только на предоставленные данные.

Формат вывода: plain text (не Markdown-код).
"""

writer_agent = Agent(
    name="Writer",
    model=config.WRITER_MODEL,
    instructions=WRITER_INSTRUCTIONS,
    functions=[],
)


# ---------------------------------------------------------------------------
# EditorAgent — проверка качества статьи
# ---------------------------------------------------------------------------
EDITOR_INSTRUCTIONS = """
Ты — EditorAgent. Проверь качество статьи по следующим критериям:
1. Соответствие теме
2. Логическая структура
3. Отсутствие фактических ошибок
4. Грамматика и стиль
5. Полнота раскрытия

Верни результат в строгом формате:
APPROVED — если статья соответствует всем критериям.
REVISION_REQUIRED: <конкретные замечания> — если требуется доработка.

Будь строгим, но справедливым. Если статья хорошая — одобряй.
"""

editor_agent = Agent(
    name="Editor",
    model=config.EDITOR_MODEL,
    instructions=EDITOR_INSTRUCTIONS,
    functions=[],
)


# ---------------------------------------------------------------------------
# PublisherAgent — финальная обработка и сохранение статьи
# ---------------------------------------------------------------------------
PUBLISHER_INSTRUCTIONS = """
Ты — PublisherAgent. Твоя задача — оформить готовую статью в читаемый Markdown и сохранить её.

Требования к финальному форматированию:
1. Заголовок первого уровня: "# Название статьи"
2. Разделы второго уровня: "## Название раздела"
3. Подразделы третьего уровня: "### Название подраздела"
4. Списки и выделения текста используй по необходимости

После форматирования обязательно вызови save_article для сохранения.

Финальный ответ: верни путь к сохранённому файлу.
"""

publisher_agent = Agent(
    name="Publisher",
    model=config.PUBLISHER_MODEL,
    instructions=PUBLISHER_INSTRUCTIONS,
    functions=[save_article],
)
